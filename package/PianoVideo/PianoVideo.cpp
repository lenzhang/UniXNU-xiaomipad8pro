IOService *PianoVideo::probe(IOService *provider, SInt32 *score)
{
  readArgs();
  if (!gArgs.level || !OSDynamicCast(IOPlatformExpertDevice, provider)) return nullptr;
  return IOService::probe(provider, score);
}

bool PianoVideo::start(IOService *provider)
{
  if (!IOService::start(provider)) return false;
  note("start: piano-video=%u cc=%u smmu=%u carveout=%u delay=%u repeat=%u samples=%u (Iris %#llx, VIDEO_CC %#llx, SPI %u, streams "
       "%#x/%#x, carveout %#llx)",
       gArgs.level, gArgs.cc, gArgs.smmu, gArgs.carveout, gArgs.delay, gArgs.repeat, gArgs.samples, (unsigned long long)kIris,
       (unsigned long long)kVideoCc, kIrisSpi, kStreamFirst, kStreamSecond, (unsigned long long)kCarveout);
  if (gArgs.level > 4) note("piano-video=%u: the highest level is 4 (docs/drivers/video.md section 8); running the survey only", gArgs.level);
  if (gArgs.level >= 2 && gArgs.level <= 4)
    note("levels 2-4: cycles=%u hold-ms=%u idle-ms=%u resumes=%u unload=%u stop=%u mmcx-floor=%#x", gArgs.cycles, gArgs.holdMs,
         gArgs.idleMs, gArgs.resumes, gArgs.unload, gArgs.stop, gArgs.mmcxFloor);
  note("level 1: loads only, nothing written");
  setProperty("piano-video", gArgs.level, 32);
  thread_t t = nullptr;
  if (kernel_thread_start(&PianoVideo::thread, this, &t) != KERN_SUCCESS) {
    stage(-1, "no thread");
    return true;
  }
  thread_deallocate(t);
  return true;
}

void PianoVideo::thread(void *self, wait_result_t)
{
  thread_set_thread_name(current_thread(), "piano-video");
  static_cast<PianoVideo *>(self)->run();
}

void PianoVideo::run()
{
  if (gArgs.delay) {
    note("waiting %u s", gArgs.delay);
    IOSleep(gArgs.delay * 1000);
  }
  unsigned loads = 0;
  Clocks c;
  stage(1, "GCC video branches (read only)");
  surveyGcc(c, load, &loads);
  reportGcc(c);
  stage(2, gArgs.cc ? "VIDEO_CC behind GCC's video AHB (read only)" : "VIDEO_CC skipped (piano-video-cc=0)");
  surveyVideoCc(c, load, gArgs.cc, &loads);
  if (c.ccRead) reportVideoCc(c);
  note("gate: %s", c.why);
  Core r;
  if (c.controller) {
    stage(3, "the core's controller registers (and the codec's idle words when its domain is on), read only");
    r = surveyCore(c, load, &loads);
  } else {
    stage(3, "the core skipped: its gate is closed");
  }
  reportCore(c, r);
  const CoreState s = coreState(c, r);
  note("core: %s: %s", coreStateName(s), coreVerdict(s));
  SmmuSurvey m;
  if (gArgs.smmu) {
    stage(4, gArgs.smmu >= 2 ? "SMMU streams 0x1940-0x194f and their banks (read only)" : "SMMU streams 0x1940-0x194f (global pages, read only)");
    m = surveySmmu(gArgs.smmu, [](uint32_t off) { return load(kSmmu + off); });
    reportSmmu(m);
  }
  Carveout fw;
  if (gArgs.carveout) {
    stage(5, "the firmware carveout's first words (read only; memory XNU does not own)");
    fw = surveyCarveout(load, &loads);
    note("carveout %#llx: %08x %08x %08x %08x %08x %08x %08x %08x: %s", (unsigned long long)kCarveout, fw.words[0], fw.words[1],
         fw.words[2], fw.words[3], fw.words[4], fw.words[5], fw.words[6], fw.words[7], carveoutVerdict(fw));
  }
  char summary[240];
  summarize(c, r, m, summary, sizeof summary);
  setProperty("piano-video-survey", summary);
  note("summary: %s", summary);
  for (uint32_t i = 1; gArgs.repeat && i <= gArgs.samples; ++i) {
    IOSleep(gArgs.repeat * 1000);
    unsigned again = 0;
    const Clocks k = surveyClocks(load, gArgs.cc, &again);
    note("sample %u (+%u s): gcc ahb %08x axi0 %08x axi1 %08x; mvs0c gdsc %08x mvs0 gdsc %08x pll0 mode %08x mvs0 %08x", i, i * gArgs.repeat,
         k.gccAhb, k.gccAxi0, k.gccAxi1, k.mvs0cGdsc, k.mvs0Gdsc, k.pllMode, k.mvs0);
  }
  stage(6, "done");
  note("done: %llu MMIO loads, %llu stores; %u pages mapped, %u map failures", (unsigned long long)gLoads, (unsigned long long)gStores,
       gPageCount, gMapFailures);
  if (gArgs.level >= 2 && gArgs.level <= 4) bringup();
  unmapAll();   // the register pages only: V3's steady state keeps its UC region and table (KernelHw), and a later level maps again
}

void PianoVideo::bringup()
{
  Options o;
  o.level = gArgs.level;
  o.cycles = gArgs.cycles;
  o.holdMs = gArgs.holdMs;
  o.idleMs = gArgs.idleMs;
  o.resumes = gArgs.resumes;
  o.unload = gArgs.unload != 0;
  o.stop = int(gArgs.stop);
  o.mmcxFloor = gArgs.mmcxFloor;
  note("level %u: writes start here; every register write is logged the first time it is written", gArgs.level);
  const uint64_t loads0 = gLoads, stores0 = gStores;
  const int rc = gBringup.run(o);
  setProperty("piano-video-bringup", gBringup.rep.summary);
  note("bring-up: %s", gBringup.rep.summary);
  note("bring-up %s: %llu MMIO loads, %llu stores (%u distinct writes logged, %u repeats); %u pages mapped, %u map failures; DRV-2 "
       "requests %u",
       rc ? "FAILED" : "done", (unsigned long long)(gLoads - loads0), (unsigned long long)(gStores - stores0), gBringup.log.logged,
       gBringup.log.repeats, gPageCount, gMapFailures, gBringup.votes.requests);
}
