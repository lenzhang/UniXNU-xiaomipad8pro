// piano (Xiaomi Pad 8 Pro, SM8750) board glue of the A830 driver. Derived from UniXNU-Pagani_SM8750 package/PaganiGpuBoard.cpp
// (25b1109, BSD-2-Clause-Patent, the OnePlus 13T's board): it fills Adreno830Board from the generated device-tree constants
// (PianoGpuInputs.h, tooling/k27/gen-piano-gpu-inputs.py) and the embedded firmware, parses the boot arguments and runs
// adreno830_start(). Every hardware action belongs to the driver. Changes against the 13T board:
//  - the boot arguments are piano-gpu-* (and piano-screenoff, piano-diag): the getter maps the driver's pagani-* names, so the driver's
//    knob table stays as upstream ships it;
//  - the level of piano-gpu (PianoA830.cpp) decides the run: 1 stops after S0 whatever piano-gpu-stop says (S0 only reads: pins,
//    cmd-db, SMEM socinfo, the speed-bin fuse, the level and vote tables, the GMU image), 2 runs S1..S10 (piano-gpu-stop=N stops after
//    S_N) with the diagnostic overlay rows (piano-gpu-status=2) unless told otherwise;
//  - the SoC id: piano's boot DT names SoC 639 and the stock DT lists 618 and 639 (the 13T measured 618); the SMEM socinfo value is
//    read first (the same two SMEM ranges S0 reads) and taken when it is one of the DT's SoCs, so S0's identity check stays a check;
//  - started from the native kext's thread (PianoA830.cpp), not from Stage7Probe; pagani-gpu-async has no meaning here.
