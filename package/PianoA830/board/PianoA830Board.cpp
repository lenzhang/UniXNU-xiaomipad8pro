Adreno830Board board;
unsigned runLevel;

static_assert(PIANO_GPU_IRQ_SMMU_CB_COUNT == 4 && PIANO_GPU_DDR_KBPS_COUNT <= 255 && PIANO_GPU_CNOC_LEVELS_COUNT == 2 &&
                  PIANO_GPU_GMU_KHZ_COUNT == 2 && PIANO_GPU_GMU_VLVL_COUNT == 2 && PIANO_GPU_BIN_COUNT == Adreno830BinCount &&
                  PIANO_GPU_WINDOW_LLCC_COUNT == Adreno830LlccWindows,
              "generated table sizes match Adreno830Board");
static_assert(PIANO_GPU_BIN0_COUNT <= Adreno830LevelMax && PIANO_GPU_BIN1_COUNT <= Adreno830LevelMax &&
                  PIANO_GPU_BIN2_COUNT <= Adreno830LevelMax && PIANO_GPU_BIN3_COUNT <= Adreno830LevelMax &&
                  PIANO_GPU_BIN4_COUNT <= Adreno830LevelMax && PIANO_GPU_BIN5_COUNT <= Adreno830LevelMax &&
                  PIANO_GPU_COMMON_LEVEL_COUNT <= PIANO_GPU_BIN0_COUNT,
              "power-level bins fit the driver's tables");
const uint32_t ddrKbps[] = PIANO_GPU_DDR_KBPS;
const Adreno830Level bin0[] = PIANO_GPU_BIN0_LEVELS, bin1[] = PIANO_GPU_BIN1_LEVELS, bin2[] = PIANO_GPU_BIN2_LEVELS,
                     bin3[] = PIANO_GPU_BIN3_LEVELS, bin4[] = PIANO_GPU_BIN4_LEVELS, bin5[] = PIANO_GPU_BIN5_LEVELS;
const Adreno830Level *const binLevels[Adreno830BinCount] = {bin0, bin1, bin2, bin3, bin4, bin5};
const uint8_t binCounts[Adreno830BinCount] = {PIANO_GPU_BIN0_COUNT, PIANO_GPU_BIN1_COUNT, PIANO_GPU_BIN2_COUNT,
                                              PIANO_GPU_BIN3_COUNT, PIANO_GPU_BIN4_COUNT, PIANO_GPU_BIN5_COUNT};
const uint32_t socIds[] = PIANO_GPU_SOC_IDS;

Adreno830Firmware image(const uint8_t *bytes, uint64_t length, const uint8_t (&pin)[32])
{
  Adreno830Firmware firmware = {bytes, length, {}};
  for (unsigned i = 0; i < 32; ++i) firmware.sha256[i] = pin[i];
  return firmware;
}

void fillBoard(Adreno830Board *b)
{
  *b = {};
  b->magic = Adreno830BoardMagic;
  b->version = Adreno830BoardVersion;
  b->gpu = PIANO_GPU_WINDOW_GPU;
  b->rscc = PIANO_GPU_WINDOW_RSCC;
  b->cx_dbgc = PIANO_GPU_WINDOW_CX_DBGC;
  b->cx_misc = PIANO_GPU_WINDOW_CX_MISC;
  b->gmu = PIANO_GPU_WINDOW_GMU;
  b->gmu_ao = PIANO_GPU_WINDOW_GMU_AO;
  b->gpucc = PIANO_GPU_WINDOW_GPUCC;
  b->gcc = PIANO_GPU_WINDOW_GCC;
  b->smmu = PIANO_GPU_WINDOW_SMMU;
  b->cmd_db = PIANO_GPU_WINDOW_CMD_DB;
  b->smem = PIANO_GPU_WINDOW_SMEM;
  b->zap = PIANO_GPU_WINDOW_ZAP;
  b->qfprom = PIANO_GPU_WINDOW_QFPROM;
  b->rsc_drv2 = PIANO_GPU_WINDOW_RSC_DRV2;
  b->aoss_msgram = PIANO_GPU_WINDOW_AOSS_MSGRAM;
  b->ipcc = PIANO_GPU_WINDOW_IPCC;
  b->tsens_tm = PIANO_GPU_WINDOW_TSENS_TM;
  const Adreno830Window llcc[] = PIANO_GPU_WINDOW_LLCC;
  for (unsigned i = 0; i < Adreno830LlccWindows; ++i) b->llcc[i] = llcc[i];
  b->chip_id = PIANO_GPU_CHIP_ID;
  b->soc_id = PIANO_GPU_SOC_ID;   // replaced by the SMEM value when that is one of the DT's SoCs (startBoard)
  b->irq_gpu = PIANO_GPU_IRQ_GPU;
  b->irq_cx_host = PIANO_GPU_IRQ_CX_HOST;
  b->irq_hfi = PIANO_GPU_IRQ_HFI;
  b->irq_gmu = PIANO_GPU_IRQ_GMU;
  b->irq_smmu_global = PIANO_GPU_IRQ_SMMU_GLOBAL;
  const uint32_t banks[] = PIANO_GPU_IRQ_SMMU_CB;
  for (unsigned i = 0; i < 4; ++i) b->irq_smmu_cb[i] = banks[i];
  b->irq_scm_waitq = PIANO_GPU_IRQ_SCM_WAITQ;
  b->sid_gpu = PIANO_GPU_SID_GPU;
  b->sid_lpac = PIANO_GPU_SID_LPAC;
  b->sid_gmu = PIANO_GPU_SID_GMU;
  // Context policy of the driver's ARCHITECTURE 4.5.4 (as the 13T): GPU on CB0 through stream-match slot 0 (LPAC slot 3), GMU on CB2
  // through slot 1; the driver moves to the next free slot when a preferred one is taken.
  b->slot_gpu = 0;
  b->slot_lpac = 3;
  b->slot_gmu = 1;
  b->cb_gpu = 0;
  b->cb_gmu = 2;
  b->smmu_actlr = 0x303;   // the 13T measured that of the DT's PIANO_GPU_SMMU_ACTLR_DT only 0x303 sticks under Gunyah; piano: needs-boot
  b->pool_mib = piano_a830_pool_default(max_mem);   // the 13T's 512 MiB was 95 % used by the login screen alone (PianoA830.h)
  b->qfprom_speedbin_offset = PIANO_GPU_QFPROM_SPEEDBIN_OFFSET;
  b->speedbin_bits = PIANO_GPU_SPEEDBIN_BITS;
  const uint32_t speed[] = PIANO_GPU_BIN_SPEED, skuCount[] = PIANO_GPU_BIN_SKU_COUNT, sku[][Adreno830BinSkus] = PIANO_GPU_BIN_SKU,
                 initial[] = PIANO_GPU_BIN_INITIAL;
  for (unsigned i = 0; i < Adreno830BinCount; ++i) {
    b->levels[i] = binLevels[i];
    b->level_count[i] = binCounts[i];
    b->initial_level[i] = uint8_t(initial[i]);
    b->bin_speed[i] = speed[i];
    b->bin_sku_count[i] = skuCount[i];
    for (unsigned k = 0; k < Adreno830BinSkus; ++k) b->bin_sku[i][k] = sku[i][k];
  }
  b->common_level_count = PIANO_GPU_COMMON_LEVEL_COUNT;
  b->ddr_kbps = ddrKbps;
  b->ddr_levels = uint8_t(PIANO_GPU_DDR_KBPS_COUNT);
  const uint32_t cnoc[] = PIANO_GPU_CNOC_LEVELS, gmuKhz[] = PIANO_GPU_GMU_KHZ, gmuVlvl[] = PIANO_GPU_GMU_VLVL;
  for (unsigned i = 0; i < 2; ++i) {
    b->cnoc_levels[i] = cnoc[i];
    b->gmu_khz[i] = gmuKhz[i];
    b->gmu_vlvl[i] = gmuVlvl[i];
  }
  b->ubwc_mode = PIANO_GPU_UBWC_MODE;
  b->min_access_length = PIANO_GPU_MIN_ACCESS_LENGTH;
  b->highest_bank_bit = 16;   // Gen8 constant (the driver's ARCHITECTURE 3.2 D, 4.14.3), not a DT value
  b->gmu_fw = image(native_adreno_firmware_image, native_adreno_firmware_image_size, PIANO_GPU_FW_GMU_SHA256);
  b->sqe_fw = image(native_adreno_sqe_firmware_image, native_adreno_sqe_firmware_image_size, PIANO_GPU_FW_SQE_SHA256);
  b->aqe_fw = image(native_adreno_aqe_firmware_image, native_adreno_aqe_firmware_image_size, PIANO_GPU_FW_AQE_SHA256);
  b->zap_fw = image(native_adreno_zap_image, native_adreno_zap_image_size, PIANO_GPU_FW_ZAP_SHA256);
}

// The driver's names (Adreno830KnobTable) are "pagani-gpu-*", "pagani-screenoff", "pagani-diag": piano's are the same with "piano-".
bool bootArgument(void *, const char *name, uint32_t *value)
{
  char piano[48];
  if (!strncmp(name, "pagani-", 7)) {
    snprintf(piano, sizeof piano, "piano-%s", name + 7);
    name = piano;
  }
  if (runLevel < 2 && !strcmp(name, "piano-gpu-stop")) {   // piano-gpu=1: S0 only, whatever was asked
    *value = 0;
    return true;
  }
  if (PE_parse_boot_argn(name, value, sizeof *value)) return true;
  if (runLevel >= 2 && !strcmp(name, "piano-gpu-status")) {   // the diagnostic page rows in the log by default
    *value = 2;
    return true;
  }
  return false;
}

// SMEM socinfo through a mapping of the board's SMEM window (the two ranges Sm8750SocInfoRead touches, as S0 does).
int socRead(void *context, uint32_t offset, uint32_t *value)
{
  const Adreno830Window smem = PIANO_GPU_WINDOW_SMEM;
  if ((offset & 3) || uint64_t(offset) + 4 > smem.bytes) return 1;
  *value = *reinterpret_cast<volatile const uint32_t *>(static_cast<volatile uint8_t *>(context) + offset);
  return 0;
}

uint32_t measuredSocId(uint32_t *found)
{
  *found = 0;
  const Adreno830Window smem = PIANO_GPU_WINDOW_SMEM;
  IODeviceMemory *memory = IODeviceMemory::withRange(smem.phys, smem.bytes);
  IOMemoryMap *map = memory ? memory->map(kIOMapAnywhere | kIOMapInhibitCache) : nullptr;
  if (memory) memory->release();
  if (!map) return PIANO_GPU_SOC_ID;
  Sm8750SocInfoIo io = {reinterpret_cast<void *>(map->getVirtualAddress()), socRead};
  Sm8750SocInfo info = {};
  const Sm8750SocInfoStatus status = Sm8750SocInfoRead(&io, &info);
  map->release();
  if (status != Sm8750SocInfoOk) return PIANO_GPU_SOC_ID;
  *found = info.id;
  for (uint32_t id : socIds)
    if (info.id == id) return id;
  return PIANO_GPU_SOC_ID;
}
