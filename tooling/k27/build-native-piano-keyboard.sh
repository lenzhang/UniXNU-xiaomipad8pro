#!/bin/bash
# Build package/PianoKeyboard (the Xiaomi keyboard cover: Nanosic WN8030 over bit-banged I2C; keyboard + consumer keys + touchpad as a
# pointer) as a k27 native kext: the host tests first (tests/keyboard_host.cpp: the WN8030 codec, the I2C engine on a bus model, the
# pointer, the descriptors), then the MCU image staged and embedded, then the objects in out/native-kexts/PianoKeyboard for
# tooling/k27/kext/PianoKeyboard.json. Prints out/k27/kext/PianoKeyboard.json (resolved) last, for a test KC:
#   PIANO_EXTRA_KEXTS=$(tooling/k27/build-native-piano-keyboard.sh | tail -1) PIANO_EXTRA_ARGS="piano-keyboard=1" tooling/k27/build-native-image.sh
# Inert without the boot argument piano-keyboard (package/PianoKeyboard/PianoKeyboard.cpp).
#   environment: K27_TREE (the k27 build tree, read only: compile recipes, out/x12377/inc-hid), K27_OBJ (default k27-native-obj),
#                CXX (host compiler for the tests), PIANO_KEYBOARD_FW (MCU_Upgrade.bin; default ../xiaomipad-8pro-mainline's
#                firmware/nanosic/piano/MCU_Upgrade.bin), PIANO_KEYBOARD_NO_FIRMWARE=1 (build without it: step 5 then stops)
# The image (the stock OS3.0.303.0 odm_a MCU_Upgrade.bin, 83,436 bytes, pinned below as xiaomipad-8pro-mainline firmware/piano-input.json
# pins it) is never committed: it is copied into the ignored out/native-kexts/PianoKeyboard/firmware and .incbin'd from there.
set -euo pipefail
D=$(cd "$(dirname "$0")/../.." && pwd)
K=${K27_TREE:-$HOME/Downloads/XiaomiPad8Pro-Ubuntu/droidvm-build/macOS-DroidVM}
HID=$K/out/x12377/inc-hid
P=$D/package/PianoKeyboard; O=$D/out/native-kexts/PianoKeyboard
[ -f "$HID/IOKit/hid/IOHIDDevice.h" ] || { echo "Error: no IOKit/hid headers at $HID" >&2; exit 1; }
mkdir -p "$O/host-tests" "$O/gen" "$O/firmware" "$D/out/k27/kext"
FW_BYTES=83436 FW_SHA=c03d6b650cb85a983359c6686d831875df10ee1206fd31afc1403baefeb7e407
FW=${PIANO_KEYBOARD_FW:-$D/../xiaomipad-8pro-mainline/firmware/nanosic/piano/MCU_Upgrade.bin}
[ -f "$FW" ] || FW=$HOME/Downloads/XiaomiPad8Pro-Ubuntu/xiaomipad-8pro-mainline/firmware/nanosic/piano/MCU_Upgrade.bin   # a worktree
GEN=$O/gen/PianoKeyboardFirmware.c
if [ "${PIANO_KEYBOARD_NO_FIRMWARE:-0}" = 1 ]; then
  rm -f "$O/firmware/MCU_Upgrade.bin"
  printf '%s\n' '// Generated by tooling/k27/build-native-piano-keyboard.sh: built without the MCU image (step 5 stops).' \
    '__asm__(".section __DATA,__const\n.p2align 3\n.globl _piano_keyboard_firmware\n_piano_keyboard_firmware:\n.quad 0\n.globl _piano_keyboard_firmware_size\n_piano_keyboard_firmware_size:\n.quad 0\n");' > "$GEN"
else
  [ -f "$FW" ] || { echo "Error: no MCU_Upgrade.bin ($FW); PIANO_KEYBOARD_FW=PATH or PIANO_KEYBOARD_NO_FIRMWARE=1" >&2; exit 1; }
  [ "$(wc -c < "$FW" | tr -d ' ')" = "$FW_BYTES" ] && [ "$(shasum -a 256 "$FW" | cut -d' ' -f1)" = "$FW_SHA" ] \
    || { echo "Error: $FW is not the pinned image ($FW_BYTES bytes, sha256 $FW_SHA)" >&2; exit 1; }
  cmp -s "$FW" "$O/firmware/MCU_Upgrade.bin" || cp "$FW" "$O/firmware/MCU_Upgrade.bin"
  printf '%s\n' '// Generated by tooling/k27/build-native-piano-keyboard.sh: the pinned MCU image from the ignored out/ copy (never committed).' \
    "__asm__(\".section __DATA,__const\\n.p2align 3\\n.globl _piano_keyboard_firmware\\n_piano_keyboard_firmware:\\n.incbin \\\"$O/firmware/MCU_Upgrade.bin\\\"\\n.p2align 3\\n.globl _piano_keyboard_firmware_size\\n_piano_keyboard_firmware_size:\\n.quad $FW_BYTES\\n\");" > "$GEN"
fi
"${CXX:-c++}" -std=c++20 -Wall -Wextra -Werror -I "$P" "$P/tests/keyboard_host.cpp" -o "$O/host-tests/keyboard_host"
"$O/host-tests/keyboard_host" ${PIANO_KEYBOARD_NO_FIRMWARE:+--no-firmware} "$O/firmware/MCU_Upgrade.bin" \
  || { echo "Error: PianoKeyboard host tests failed" >&2; exit 1; }
python3 "$D/tooling/k27/build-native-kext.py" PianoKeyboard "$P/PianoKeyboard.cpp" "$D/tooling/k27/NativeKextGlue.cpp" "$GEN" \
  -I "$P" -I "$HID" -I "$K/out/x12377/inc-gfx" -I "$K/out/x12377/storage-abi/include" -D U:TARGET_OS_OSX -D TARGET_OS_OSX=1 \
  --obj "${K27_OBJ:-k27-native-obj}" >&2
KERNEL=${K27_KERNEL:-$K/out/k27/kernel-k27-0059-native.macho}
# IOHIDDevice's symbols come from IOHIDFamily (a library of the descriptor), resolved by the KC link.
[ ! -f "$KERNEL" ] || python3 "$D/tooling/k27/check-kext-imports.py" "$O/objects.json" "$KERNEL" --library-prefix __ZN11IOHIDDevice \
  --library-prefix __ZNK11IOHIDDevice --library-prefix __ZTV11IOHIDDevice | cut -c1-160 >&2
sed "s#@OUT@#$D/out#" "$D/tooling/k27/kext/PianoKeyboard.json" > "$D/out/k27/kext/PianoKeyboard.json"
echo "$D/out/k27/kext/PianoKeyboard.json"
