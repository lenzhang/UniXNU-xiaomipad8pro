def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('command', choices=('header', 'thunks', 'check-kc', 'check-object', 'self-test', 'show'))
    parser.add_argument('path', nargs='?')
    parser.add_argument('--abi', type=Path, default=DEFAULT_ABI)
    parser.add_argument('--out', type=Path)
    parser.add_argument('--thunks', type=Path, help='check-object: the assembled xhci-thunks.o that binds the inherited slots')
    args = parser.parse_args()
    try:
        abi = load_abi(args.abi)
        if args.command == 'header':
            if not args.out:
                sys.exit('header needs --out DIR')
            path = write_header(abi, args.out)
            print(f'xHCI ABI: {path} ({len(abi["slots"])} slots, instance size {abi["instance_size"]}, '
                  f'{len(abi["methods"])} private declarations)')
        elif args.command == 'thunks':
            if not args.out or not args.path:
                sys.exit('thunks needs OBJECT.o and --out DIR')
            text, plan = thunk_assembly(abi, MachObject(bytearray(Path(args.path).read_bytes())))
            path = Path(args.out) / 'xhci-thunks.S'
            path.write_text(text)
            print(f'xHCI ABI: {path} ({len(plan)} thunk(s) binding {sum(len(s) for _, s in plan.values())} inherited slots to the '
                  f'collection\'s symbols)')
        elif args.command == 'check-kc':
            print(f'xHCI ABI: {Path(args.path).name}: {check_kc(abi, args.path, args.abi)}')
        elif args.command == 'check-object':
            print(f'xHCI ABI: {Path(args.path).name}: {check_object(abi, args.path, thunks=args.thunks)}')
        elif args.command == 'self-test':
            print(self_test(abi))
        else:
            p = abi['provenance']
            print(f'AppleUSBXHCI of {p["kernelcache"]}\n  sha256 {p["kernelcache_sha256"]}\n  {len(abi["slots"])} slots, '
                  f'instance size {abi["instance_size"]}, fixture {p["fixture_source"]} ({p["fixture_sha256"][:8]}...)')
            for slot, macro in sorted(abi['macros'].items(), key=lambda kv: int(kv[0])):
                m = abi['methods'][slot]
                print(f'  slot {slot:>3} diversity {abi["slots"][int(slot)][1]}  {macro} = '
                      f'{m["returns"]} {m["name"]}({m["parameters"]})  [{abi["slots"][int(slot)][2]}]')
    except Refused as e:
        sys.exit(f'xHCI ABI gate: {e}')


if __name__ == '__main__':
    main()
