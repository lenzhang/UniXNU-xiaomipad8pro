#!/usr/bin/env python3
"""The AppleUSBXHCI ABI of one kernel collection: the declarations PianoXhciHost compiles against, and the gates that refuse a
changed collection or a drifted vtable (docs/drivers/usb-host.md §5.4, path A2).

    xhci-abi.py header   [--abi DATA.json] --out DIR            write OriginalUsbXhciABI.h (a build output, never committed)
    xhci-abi.py check-kc [--abi DATA.json] KC.bin               the collection is the one the data file was made from
    xhci-abi.py check-object [--abi DATA.json] OBJECT.o         the compiled subclass's vtable: 427 slots, every PAC diversity the
                                                                collection's, only the three intended slots ours
    xhci-abi.py self-test                                       the gates refuse a changed collection, a changed diversity, an
                                                                extra slot, a stolen slot and a missing one
    xhci-abi.py show     [--abi DATA.json]                      the three overridden slots and the data file's provenance

The data file is `data/usb-xhci/abi-26C5035r-mac17j.json` (numbers and names only, its provenance in `data/usb-xhci/README.md`):
the class's 427 vtable slots with the PAC diversity and the symbol each one must reach, the instance size, the synthetic
declarations of the private slots, and the three the Piano subclass implements (slot 292 the desired power state, 419 the 64-bit
register read, 421 the 64-bit register write).

Why each gate exists (private/host-checks/20261114-xhci/REPORT.md §5): the kernel-collection builder's own vtable check compares
inherited *targets*, not PAC diversities, not the slot count and not the instance size, so "0 problem slots" does not prove the
A2 ABI. An override whose fabricated declaration hashes to another discriminator links and then traps on its first virtual call.
A new macOS seed would silently move the slots, so the collection's SHA-256 is pinned here too.

No Apple code or Apple bytes are read into any output: `check-kc` reads the collection's vtable fixups and the instance size that
its OSMetaClass constructor passes, and compares them with the data file; nothing of the collection is copied out.
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DEFAULT_ABI = REPO / 'data/usb-xhci/abi-26C5035r-mac17j.json'
SUBCLASS = 'PianoXhciHost'
# The mangled vtable symbol of the subclass, and the two words (offset-to-top, type info) before its address point.
SUBCLASS_VTABLE = f'__ZTV{len(SUBCLASS)}{SUBCLASS}'
VTABLE_PREFIX_WORDS = 2
# Mach-O arm64 relocation kinds this tool needs (the rest are not expected in a vtable or thunk section).
ARM64_RELOC_UNSIGNED, BRANCH26, ARM64_RELOC_AUTHENTICATED_POINTER = 0, 2, 11

HEADER_TOP = f'''// Generated by tooling/k27/xhci-abi.py from data/usb-xhci/abi-26C5035r-mac17j.json: build output, never committed.
// The AppleUSBXHCI declarations PianoXhciHost derives from (docs/drivers/usb-host.md §5.4). Opaque private storage only: no Apple
// field layout, no Apple code. Every virtual slot of the class must be declared, in its order, so that the compiler lays the
// subclass's vtable out exactly like the collection's and signs each entry with the introducing declaration's discriminator.
#pragma once
#include <IOKit/IOService.h>
'''


class Refused(Exception):
    pass


def load_abi(path):
    abi = json.loads(Path(path).read_text())
    if len(abi['slots']) != 427 or abi['base_slots'] != 272:
        raise Refused(f'{path}: {len(abi["slots"])} slots, base {abi["base_slots"]}: not the AppleUSBXHCI layout (427 / 272)')
    if sorted(abi['macros']) != sorted(('292', '419', '421')):
        raise Refused(f'{path}: the overridden slots are {sorted(abi["macros"])}, not 292 / 419 / 421')
    return abi


# The slots of IOService (and its bases) that the original class or its own base overrides: declared in the generated class so that
# our subclass's vtable holds the collection's entry in each of them. (mangled suffix of the method, declaration without the
# trailing semicolon). The declarations are IOService's own methods, so the slots stay in their places and keep IOService's
# discriminators; the mangled suffix finds the slot in the data file, whose symbol - often a method of the class's own base,
# AppleUSBHostController - becomes the assembler label of the declaration, so the reference names what the collection has there.
# The structors (slots 0, 1 and 7) are not here: a concrete subclass has its own.
SERVICE_OVERRIDES = [
    ('4freeEv', 'void free()'),
    ('4initEP12OSDictionary', 'bool init(OSDictionary *properties = nullptr)'),
    ('13setPropertiesEP8OSObject', 'IOReturn setProperties(OSObject *)'),
    ('12didTerminateEP9IOServicejPb', 'bool didTerminate(IOService *, IOOptionBits, bool *)'),
    ('18systemWillShutdownEj', 'void systemWillShutdown(IOOptionBits)'),
    ('15registerServiceEj', 'void registerService(IOOptionBits options = 0)'),
    ('5startEP9IOService', 'bool start(IOService *)'),
    ('4stopEP9IOService', 'void stop(IOService *)'),
    ('4openEP9IOServicejPv', 'bool open(IOService *, IOOptionBits options = 0, void *arg = nullptr)'),
    ('5closeEP9IOServicej', 'void close(IOService *, IOOptionBits options = 0)'),
    ('10handleOpenEP9IOServicejPv', 'bool handleOpen(IOService *, IOOptionBits, void *)'),
    ('11handleCloseEP9IOServicej', 'void handleClose(IOService *, IOOptionBits)'),
    ('12handleIsOpenEPK9IOService', 'bool handleIsOpen(const IOService *) const'),
    ('9terminateEj', 'bool terminate(IOOptionBits options = 0)'),
    ('18matchPropertyTableEP12OSDictionaryPi', 'bool matchPropertyTable(OSDictionary *, SInt32 *)'),
    ('6attachEP9IOService', 'bool attach(IOService *)'),
    ('11getWorkLoopEv', 'IOWorkLoop *getWorkLoop() const'),
    ('7messageEjP9IOServicePv', 'IOReturn message(UInt32, IOService *, void *arg = nullptr)'),
    ('6PMstopEv', 'void PMstop()'),
    ('13setPowerStateEmP9IOService', 'IOReturn setPowerState(unsigned long, IOService *)'),
    ('27maxCapabilityForDomainStateEm', 'unsigned long maxCapabilityForDomainState(IOPMPowerFlags)'),
    ('31initialPowerStateForDomainStateEm', 'unsigned long initialPowerStateForDomainState(IOPMPowerFlags)'),
    ('22powerStateWillChangeToEmmP9IOService', 'IOReturn powerStateWillChangeTo(IOPMPowerFlags, unsigned long, IOService *)'),
    ('21powerStateDidChangeToEmmP9IOService', 'IOReturn powerStateDidChangeTo(IOPMPowerFlags, unsigned long, IOService *)'),
]
# The slots a concrete Libkern subclass always fills with its own: the two destructors and getMetaClass.
STRUCTOR_SLOTS = (0, 1, 7)
# The classes of the kernel itself in the prefix. A slot held by one of them is our kernel's to fill: it is the only place where
# the name may differ from the collection's and still be right, because our kernel is a source build of xnu-12377 with the k27
# patches, not the kernel the collection shipped (27.3's OSMetaClassBase has `Dispatch(IORPC)` where ours has a reserved slot).
# The PAC diversity still has to match, or Apple's call site could not authenticate the entry.
KERNEL_CLASSES = ('OSObject', 'OSMetaClassBase', 'OSMetaClass', 'IORegistryEntry', 'IOService')
KERNEL_PREFIXES = tuple(f'__ZN{len(c)}{c}' for c in KERNEL_CLASSES) + tuple(f'__ZNK{len(c)}{c}' for c in KERNEL_CLASSES)


# --------------------------------------------------------------------------------------------------- the generated declarations
def slot_of_method(abi, suffix):
    """The one prefix slot whose symbol ends with this mangled method suffix (whatever class of the chain implements it)."""
    found = [s for s in range(abi['base_slots']) if abi['slots'][s][2].endswith(suffix)]
    if len(found) != 1:
        raise Refused(f'{suffix}: {len(found)} prefix slots of the data file end with it ({found})')
    return found[0]


def service_override_slots(abi):
    """The prefix slots covered by SERVICE_OVERRIDES, and the ones the data file says the chain overrides. Every overridden slot
    must be declared, or our vtable would hold the kernel's own implementation where the collection has the controller's."""
    covered = {slot_of_method(abi, suffix): declaration for suffix, declaration in SERVICE_OVERRIDES}
    kernel = ('__ZN8OSObject', '__ZNK8OSObject', '__ZN15OSMetaClassBase', '__ZNK15OSMetaClassBase', '__ZN15IORegistryEntry',
              '__ZNK15IORegistryEntry', '__ZN9IOService', '__ZNK9IOService')
    overridden = {s for s in range(abi['base_slots']) if not abi['slots'][s][2].startswith(kernel)} - set(STRUCTOR_SLOTS)
    missing = sorted(overridden - set(covered))
    if missing:
        raise Refused('the chain overrides prefix slot(s) this tool does not declare: '
                      + ', '.join(f'{s} ({abi["slots"][s][2]})' for s in missing))
    extra = sorted(set(covered) - overridden)
    if extra:
        raise Refused(f'declared prefix slot(s) the chain does not override: {extra}')
    return covered


def header(abi):
    """The class declaration our subclass derives from.

    Two kinds of slot need a name here. The class's own private slots are **fabricated**: the declaration name is chosen so that
    its mangled form hashes to the slot's PAC diversity, which is all the vtable needs (no Apple field or body is known or used).
    The slots of IOService that the original chain overrides are declared with IOService's own method names, so that they stay in
    their places and keep IOService's discriminators.

    The compiler emits a reference to `AppleUSBXHCI::<declared name>` in every slot we do not implement, and no collection defines
    those names (the collection has, say, `AppleUSBHostController::setProperties` in slot 100). They are bound by the thunks of
    `thunk_assembly()` below; an assembler label on the declaration cannot do it, because clang then signs the slot with the hash
    of the label instead of the hash of the declaration, which is exactly the discriminator that must not change.
    """
    methods = {int(k): v for k, v in abi['methods'].items()}
    macros = {int(k): v for k, v in abi['macros'].items()}
    text = HEADER_TOP
    for slot in sorted(macros):
        text += f'#define {macros[slot]} {methods[slot]["name"]}\n'
    text += f'''
class AppleUSBXHCI : public IOService {{
  OSDeclareAbstractStructors(AppleUSBXHCI)
  unsigned char originalPrivate[{abi['instance_size']} - sizeof(IOService)];

public:
  // The slots of IOService that the original chain overrides, with the symbol the collection has in each.
'''
    for slot, declaration in sorted(service_override_slots(abi).items()):
        text += f'  {declaration} override;   // slot {slot}: {abi["slots"][slot][2]}\n'
    text += '''
  // The class's own virtual slots, in their order. Only the three the subclass implements are ours; every other one is a
  // fabricated declaration labelled with the collection's symbol for that slot.
'''
    for slot in range(abi['base_slots'], len(abi['slots'])):
        m = methods[slot]
        text += f'  virtual {m["returns"]} {m["name"]}({m["parameters"]});\n'
    text += f'}};\nstatic_assert(sizeof(AppleUSBXHCI) == {abi["instance_size"]}, "the original controller\'s instance size");\n'
    return text


def write_header(abi, out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    path = out / 'OriginalUsbXhciABI.h'
    path.write_text(header(abi))
    return path


# ------------------------------------------------------------------------------------------- gate 1: is this the pinned collection
def kc_vtable(kc, abi):
    """(targets, diversities, symbol names) of the class's vtable in the collection, from its chained fixups."""
    sys.path.insert(0, str(k27_tree() / 'scripts'))
    import fileset_kc                                     # noqa: E402  (the k27 tree is read only)
    collection = fileset_kc.Kernelcache(Path(kc).read_bytes())
    sites = {}
    for site, _raw, target, auth, diversity, addr_div, key in collection.chained_sites():
        sites[site] = (target, auth, diversity, addr_div, key)
    # every fileset entry's symbols: a target address -> the name defined there (the kernel first, so its own slots keep its name)
    symbol_of = {}
    for name in collection.entries:
        for symbol, _kind, _sect, _desc, value in collection.symbols(collection.macho(name)):
            symbol_of.setdefault(value, symbol)
    point = int(abi['vtable'], 16)
    rows = []
    for slot in range(len(abi['slots'])):
        site = sites.get(point + 8 * slot)
        if site is None:
            raise Refused(f'slot {slot}: no chained fixup at {point + 8 * slot:#x} in {kc} (not this collection)')
        target, auth, diversity, addr_div, key = site
        rows.append((target, auth, diversity, addr_div, key, symbol_of.get(target, f'+{target:#x}')))
    return rows


def kc_instance_size(kc, cls='AppleUSBXHCI', fileset='com.apple.driver.usb.AppleUSBXHCI'):
    sys.path.insert(0, str(k27_tree() / 'scripts'))
    import fileset_kc                                     # noqa: E402
    collection = fileset_kc.Kernelcache(Path(kc).read_bytes())
    want = f'__ZN{len(cls)}{cls}9MetaClassC2Ev'
    found = [v for n, _k, _s, _d, v in collection.symbols(collection.macho(fileset)) if n == want]
    if not found:
        raise Refused(f'{kc}: no {want} (no {cls} in this collection)')
    off = collection.file_offset(found[0])
    for i in range(32):
        word = int.from_bytes(collection.data[off + 4 * i:off + 4 * i + 4], 'little')
        if word & 0xffe0001f == 0x52800003:               # movz w3, #imm16 (the size the constructor passes)
            return (word >> 5) & 0xffff
    raise Refused(f'{kc}: the {cls} metaclass constructor passes no literal size')


def check_kc(abi, kc, abi_path=DEFAULT_ABI):
    """The collection must be the one the data file was made from: same SHA-256, same vtable, same instance size."""
    digest = hashlib.sha256(Path(kc).read_bytes()).hexdigest()
    pinned = abi['provenance']['kernelcache_sha256']
    if digest != pinned:
        raise Refused(f'{kc}: sha256 {digest}, the data file pins {pinned}: rebuild the ABI data for this collection '
                      f'(data/usb-xhci/README.md) — slot numbers never carry across seeds')
    rows = kc_vtable(kc, abi)
    for slot, (row, want) in enumerate(zip(rows, abi['slots'])):
        target, auth, diversity, addr_div, key, symbol = row
        if not (auth and addr_div and key == 0):
            raise Refused(f'slot {slot}: auth={auth} address-diversified={addr_div} key={key}: the data file assumes IA + address')
        if diversity != int(want[1], 16):
            raise Refused(f'slot {slot}: diversity {diversity:#06x}, the data file says {want[1]}')
        if symbol != want[2]:
            raise Refused(f'slot {slot}: reaches {symbol}, the data file says {want[2]}')
    size = kc_instance_size(kc)
    if size != int(abi['instance_size'], 16):
        raise Refused(f'instance size {size:#x}, the data file says {abi["instance_size"]}')
    return f'{len(rows)} slots and instance size {size:#x} as {Path(abi_path).name} records them'


# --------------------------------------------------------------------------- gate 2: the compiled subclass's own vtable (pre-link)
class MachObject:
    """A relocatable arm64 Mach-O: the sections, the symbols, and a section's relocations. Written for this gate; the idea (a
    build-time check of the emitted vtable against the collection's) is UniXNU-sheng's."""

    def __init__(self, data):
        magic, cpu, _sub, kind, count, _size, _flags, _r = struct.unpack_from('<8I', data, 0)
        if (magic, cpu, kind) != (0xfeedfacf, 0x100000c, 1):
            raise Refused('not a relocatable arm64 object')
        self.data = data
        self.sections, self.symbols = [], []
        offset = 32
        for _ in range(count):
            cmd, length = struct.unpack_from('<II', data, offset)
            if cmd == 0x19:                                                        # LC_SEGMENT_64
                for index in range(struct.unpack_from('<I', data, offset + 64)[0]):
                    name, seg, addr, size, off, _align, reloff, nreloc = struct.unpack_from('<16s16s2Q4I', data, offset + 72 + index * 80)
                    self.sections.append({'name': name.split(b'\0')[0].decode(), 'segment': seg.split(b'\0')[0].decode(),
                                          'addr': addr, 'size': size, 'offset': off, 'reloff': reloff, 'nreloc': nreloc,
                                          'index': len(self.sections) + 1})
            elif cmd == 2:                                                         # LC_SYMTAB
                symoff, nsyms, stroff, strsize = struct.unpack_from('<4I', data, offset + 8)
                strings = bytes(data[stroff:stroff + strsize])
                for i in range(nsyms):
                    strx, type_, sect, _desc, value = struct.unpack_from('<IBBHQ', data, symoff + i * 16)
                    self.symbols.append({'name': strings[strx:strings.index(b'\0', strx)].decode(), 'type': type_,
                                         'sect': sect, 'value': value})
            offset += length

    def symbol(self, name):
        for s in self.symbols:
            if s['name'] == name:
                return s
        return None

    def relocations(self, section):
        for i in range(section['nreloc']):
            address, word = struct.unpack_from('<II', self.data, section['reloff'] + i * 8)
            yield address, word & 0xffffff, word >> 27 & 1, word >> 28


def object_vtable(obj, symbol_name, slots):
    """[(slot, target symbol, auth, diversity, address-diversified, key)] of a vtable the object defines."""
    symbol = obj.symbol(symbol_name)
    if symbol is None or not symbol['sect']:
        raise Refused(f'the object defines no {symbol_name}')
    section = obj.sections[symbol['sect'] - 1]
    start = symbol['value'] - section['addr'] + 8 * VTABLE_PREFIX_WORDS
    # The same section holds other objects (the class's MetaClass vtable, constant data): the vtable ends at the next symbol
    # defined in this section, so a pointer past that belongs to something else and is not an added virtual method of ours.
    after = [s['value'] - section['addr'] for s in obj.symbols
             if s['sect'] == symbol['sect'] and s['value'] > symbol['value'] and s['type'] & 0x0e == 0x0e]
    end = min(after) if after else section['size']
    found = {}
    extra = []
    for address, symbolnum, extern, kind in obj.relocations(section):
        if not start <= address < end or (address - start) % 8:
            continue
        slot = (address - start) // 8
        if kind not in (ARM64_RELOC_UNSIGNED, ARM64_RELOC_AUTHENTICATED_POINTER):
            raise Refused(f'{symbol_name} slot {slot}: relocation kind {kind}, expected an authenticated pointer')
        if not extern:
            raise Refused(f'{symbol_name} slot {slot}: a local relocation (the target has no name)')
        word, = struct.unpack_from('<Q', obj.data, section['offset'] + address)
        target = obj.symbols[symbolnum]['name']
        if slot >= slots:
            extra.append((slot, target))
            continue
        found[slot] = (target, kind == ARM64_RELOC_AUTHENTICATED_POINTER, word >> 32 & 0xffff, bool(word >> 48 & 1), word >> 49 & 3)
    if extra:
        raise Refused(f'{symbol_name} has slot {extra[0][0]} ({extra[0][1]}): the subclass adds a virtual method, so the vtable is '
                      f'no longer the original\'s {slots} slots')
    missing = [s for s in range(slots) if s not in found]
    if missing:
        raise Refused(f'{symbol_name}: {len(missing)} slot(s) without a pointer (first {missing[0]}): the declarations do not cover '
                      f'the class')
    return [(s, *found[s]) for s in range(slots)]


# ------------------------------------------------------------------- the thunks that bind the inherited slots to the collection
# A fabricated declaration makes the compiler emit a reference to `AppleUSBXHCI::<that name>`, which no collection defines. Each
# such reference is defined here as a four-instruction thunk that tail-branches to the symbol the collection really has in that
# slot; the branch is a plain BRANCH26 relocation, which the kernel-collection builder resolves by name against the kept kexts
# (the same way every other import of a native kext is resolved - no address is hard-coded anywhere).
#
# A tail branch is transparent: the arguments stay in their registers, the link register still holds Apple's caller, and the
# `bti c` makes the thunk a valid landing pad for the authenticated indirect call Apple's code makes through the vtable slot.
# (UniXNU-sheng binds the same fabricated names with `bti c; b <original>` thunks over absolute addresses; ours go through the
# collection builder's name resolution instead, so no address survives a rebuild.)
THUNK_SECTION = ('__TEXT', '__text')


def thunk_plan(abi, obj):
    """{fabricated symbol: (the collection's symbol, the slots that use it)} for every slot the subclass does not implement."""
    rows = object_vtable(obj, SUBCLASS_VTABLE, len(abi['slots']))
    ours = {int(k) for k in abi['macros']} | set(STRUCTOR_SLOTS)
    plan = {}
    for slot, target, _auth, _diversity, _addr_div, _key in rows:
        if slot in ours or target == abi['slots'][slot][2]:
            continue                                       # ours, or already the collection's own name
        if target.startswith(KERNEL_PREFIXES) and abi['slots'][slot][2].startswith(KERNEL_PREFIXES):
            continue                                       # a slot of the kernel itself: our kernel's own entry belongs there
        if not target.startswith(('__ZN12AppleUSBXHCI', '__ZNK12AppleUSBXHCI')):
            raise Refused(f'slot {slot}: bound to {target}, which is neither the collection\'s {abi["slots"][slot][2]} nor a '
                          f'declaration of the generated header')
        want = abi['slots'][slot][2]
        if target in plan and plan[target][0] != want:
            raise Refused(f'{target}: used for both {plan[target][0]} and {want}')
        plan.setdefault(target, (want, []))[1].append(slot)
    return plan


def thunk_assembly(abi, obj):
    text = ('// Generated by tooling/k27/xhci-abi.py from data/usb-xhci/abi-26C5035r-mac17j.json and the compiled subclass:\n'
            '// build output, never committed. Each entry binds one fabricated declaration of OriginalUsbXhciABI.h to the symbol\n'
            '// the kernel collection has in that vtable slot, as a tail branch the collection builder resolves by name.\n'
            '.text\n.p2align 2\n')
    plan = thunk_plan(abi, obj)
    for name, (want, slots) in sorted(plan.items()):
        text += (f'// slot{"s" if len(slots) > 1 else ""} {", ".join(str(s) for s in slots)}\n'
                 f'.globl {name}\n.p2align 2\n{name}:\n  bti c\n  b {want}\n')
    return text, plan


# ------------------------------------------------------------------------------- gate 2: the compiled subclass's own vtable
def check_object(abi, path, symbol_name=SUBCLASS_VTABLE, data=None, thunks=None):
    """The compiled subclass: exactly the original's slots, every entry signed with the original's diversity, only the three
    intended slots implemented by us, and every other slot reaching the symbol the collection has there - directly, or through a
    thunk of THUNKS (the assembled xhci-thunks.o) whose only branch goes to that symbol."""
    obj = MachObject(bytearray(Path(path).read_bytes() if data is None else data))
    rows = object_vtable(obj, symbol_name, len(abi['slots']))
    ours = {int(k) for k in abi['macros']}
    # Every concrete Libkern subclass has its own destructors (slots 0 and 1) and getMetaClass (slot 7); those are not behaviour.
    structors = set(STRUCTOR_SLOTS)
    mine = f'__ZN{len(SUBCLASS)}{SUBCLASS}', f'__ZNK{len(SUBCLASS)}{SUBCLASS}'
    bound = thunk_targets(MachObject(bytearray(Path(thunks).read_bytes()))) if thunks else {}
    replaced, inherited, thunked, kernel = set(), 0, 0, []
    for slot, target, auth, diversity, addr_div, key in rows:
        want_target, want_diversity = abi['slots'][slot][2], int(abi['slots'][slot][1], 16)
        if not (auth and addr_div and key == 0):
            raise Refused(f'slot {slot} ({target}): auth={auth} address-diversified={addr_div} key={key}: not IA + address as the '
                          f'collection signs it')
        if diversity != want_diversity:
            raise Refused(f'slot {slot} ({target}): signed with {diversity:#06x}, the collection signs that slot with '
                          f'{want_diversity:#06x} (a changed declaration name, parameter list or constness)')
        if target.startswith(mine):
            if slot not in ours | structors:
                raise Refused(f'slot {slot} ({target}): the subclass implements a slot it must leave to the original '
                              f'(only {sorted(ours)} and the destructors/getMetaClass {sorted(structors)} may be ours)')
            if slot in ours:
                replaced.add(slot)
            else:
                inherited += 1
        elif slot in structors:
            raise Refused(f'slot {slot}: bound to {target}, but a concrete subclass must have its own destructors and '
                          f'getMetaClass there')
        elif target == want_target:
            inherited += 1
        elif target in bound:
            if bound[target] != want_target:
                raise Refused(f'slot {slot}: its thunk {target} branches to {bound[target]}, the collection has {want_target} there')
            thunked += 1
        elif target.startswith(KERNEL_PREFIXES) and want_target.startswith(KERNEL_PREFIXES):
            kernel.append(f'{slot} ({target} for {want_target})')
        else:
            raise Refused(f'slot {slot}: bound to {target}, the collection has {want_target} there'
                          + ('' if thunks else ' (and no thunk object was given to bind it)'))
    if replaced != ours:
        raise Refused(f'the subclass implements {sorted(replaced)}, not {sorted(ours)} '
                      f'({", ".join(f"{k}={v}" for k, v in sorted(abi["macros"].items()))})')
    note = f'; {len(kernel)} slot(s) of the kernel itself hold our kernel\'s entry: {", ".join(kernel)}' if kernel else ''
    return (f'{len(rows)} slots, {inherited} bound to the collection by name, {thunked} through a checked thunk, ours exactly '
            f'{sorted(replaced)}; every entry IA + address-diversified with the collection\'s diversity{note}')


def thunk_targets(obj):
    """{thunk symbol: the symbol its branch goes to} for every global of the assembled thunk object. A thunk must be exactly a
    `bti c` and one branch: anything else (a stray instruction, two branches, a missing relocation) is refused."""
    section = next((s for s in obj.sections if (s['segment'], s['name']) == THUNK_SECTION), None)
    if section is None:
        raise Refused(f'the thunk object has no {THUNK_SECTION[0]},{THUNK_SECTION[1]} section')
    branches = {}
    for address, symbolnum, extern, kind in obj.relocations(section):
        if kind != BRANCH26:
            raise Refused(f'the thunk object has relocation kind {kind} at {address:#x}, expected a branch')
        if not extern:
            raise Refused(f'the thunk object has a local branch at {address:#x}')
        branches[address] = obj.symbols[symbolnum]['name']
    # Global symbols only: the assembler's own local labels (ltmpN) sit at the same addresses and are not thunks.
    defined = sorted(((s['value'] - section['addr'], s['name']) for s in obj.symbols
                      if s['sect'] == section['index'] and s['type'] & 0x0f == 0x0f), key=lambda x: x[0])
    out = {}
    for i, (offset, name) in enumerate(defined):
        end = defined[i + 1][0] if i + 1 < len(defined) else section['size']
        words = [int.from_bytes(obj.data[section['offset'] + offset + 4 * w:section['offset'] + offset + 4 * w + 4], 'little')
                 for w in range((end - offset) // 4)]
        here = {a: t for a, t in branches.items() if offset <= a < end}
        if len(words) < 2 or words[0] != 0xd503245f:                       # bti c
            raise Refused(f'thunk {name}: does not begin with `bti c`')
        if len(here) != 1 or offset + 4 not in here:
            raise Refused(f'thunk {name}: {len(here)} branch relocation(s), expected exactly one right after the `bti c`')
        if words[1] & 0xfc000000 != 0x14000000:                            # b <target>
            raise Refused(f'thunk {name}: the instruction after `bti c` is {words[1]:#010x}, not an unconditional branch')
        if any(w not in (0, 0xd503201f) for w in words[2:]):               # padding only
            raise Refused(f'thunk {name}: more than `bti c` and one branch')
        out[name] = here[offset + 4]
    return out


