def self_test(abi):
    """The gates must refuse: a changed collection (another SHA-256), a changed diversity, an added slot, a stolen slot, a
    missing slot, a wrong signing key. Built from synthetic objects: no collection and no Apple file is needed."""
    problems = []
    slots = len(abi['slots'])
    ours = sorted(int(k) for k in abi['macros'])

    def fake_object(entries):
        """A minimal relocatable arm64 object with one __DATA_CONST,__const section holding SUBCLASS_VTABLE and its fixups.
        ENTRIES: {slot: (symbol, diversity, addr_div, key, kind)}."""
        names = [SUBCLASS_VTABLE] + sorted({e[0] for e in entries.values()})
        strings = b'\0' + b'\0'.join(n.encode() for n in names) + b'\0'
        offsets, at = {}, 1
        for n in names:
            offsets[n] = at
            at += len(n) + 1
        words = 8 * (VTABLE_PREFIX_WORDS + max(entries) + 1)
        body = bytearray(words)
        relocs = bytearray()
        for slot, (symbol, diversity, addr_div, key, kind) in sorted(entries.items()):
            address = 8 * (VTABLE_PREFIX_WORDS + slot)
            struct.pack_into('<Q', body, address, diversity << 32 | int(addr_div) << 48 | key << 49 | 1 << 63)
            relocs += struct.pack('<II', address, names.index(symbol) | 1 << 24 | 3 << 25 | 1 << 27 | kind << 28)
        commands = 72 + 80 + 24                                    # LC_SEGMENT_64 with one section, LC_SYMTAB
        sect_off = 32 + commands
        reloc_off = sect_off + len(body)
        symtab_off = reloc_off + len(relocs)
        symbols = bytearray()
        for i, n in enumerate(names):
            # the vtable is defined in section 1; the targets are undefined externals
            type_, sect, value = (0x0f, 1, 0) if i == 0 else (0x01, 0, 0)
            symbols += struct.pack('<IBBHQ', offsets[n], type_, sect, 0, value)
        string_off = symtab_off + len(symbols)
        data = bytearray()
        data += struct.pack('<8I', 0xfeedfacf, 0x100000c, 0, 1, 2, commands, 0, 0)
        data += struct.pack('<II16s4Q4I', 0x19, 72 + 80, b'', 0, words, sect_off, len(body), 0, 0, 1, 0)
        data += struct.pack('<16s16s2Q4I4I', b'__const', b'__DATA_CONST', 0, len(body), sect_off, 3, reloc_off,
                            len(relocs) // 8, 0, 0, 0, 0)
        data += struct.pack('<6I', 2, 24, symtab_off, len(names), string_off, len(strings))
        assert len(data) == sect_off, (len(data), sect_off)
        data += body + relocs + symbols + strings
        return data

    structors = {0: f'__ZN{len(SUBCLASS)}{SUBCLASS}D1Ev', 1: f'__ZN{len(SUBCLASS)}{SUBCLASS}D0Ev',
                 7: f'__ZNK{len(SUBCLASS)}{SUBCLASS}12getMetaClassEv'}
    good = {}
    for slot in range(slots):
        if slot in structors:
            symbol = structors[slot]
        elif slot in ours:
            symbol = f'__ZN{len(SUBCLASS)}{SUBCLASS}5slotEv'
        else:
            symbol = abi['slots'][slot][2]
        good[slot] = (symbol, int(abi['slots'][slot][1], 16), True, 0, ARM64_RELOC_AUTHENTICATED_POINTER)
    try:
        check_object(abi, None, data=fake_object(good))
    except Refused as e:
        problems.append(f'refused a correct subclass vtable: {e}')
    cases = {}
    bad = dict(good)
    bad[419] = (bad[419][0], bad[419][1] ^ 1, True, 0, ARM64_RELOC_AUTHENTICATED_POINTER)
    cases['a changed PAC diversity'] = bad
    bad = dict(good)
    bad[slots] = (f'__ZN{len(SUBCLASS)}{SUBCLASS}5extraEv', 0x1234, True, 0, ARM64_RELOC_AUTHENTICATED_POINTER)
    cases['an added virtual method'] = bad
    bad = dict(good)
    bad[400] = (f'__ZN{len(SUBCLASS)}{SUBCLASS}5resetEv', int(abi['slots'][400][1], 16), True, 0, ARM64_RELOC_AUTHENTICATED_POINTER)
    cases['a fourth slot taken from the original'] = bad
    bad = dict(good)
    del bad[300]
    cases['a slot without a pointer'] = bad
    bad = dict(good)
    bad[419] = (bad[419][0], bad[419][1], True, 1, ARM64_RELOC_AUTHENTICATED_POINTER)
    cases['another signing key'] = bad
    bad = dict(good)
    bad[419] = (bad[419][0], bad[419][1], False, 0, ARM64_RELOC_AUTHENTICATED_POINTER)
    cases['an entry that is not address-diversified'] = bad
    bad = dict(good)
    bad[200] = ('__ZN12SomeoneElse4freeEv', int(abi['slots'][200][1], 16), True, 0, ARM64_RELOC_AUTHENTICATED_POINTER)
    cases['an inherited slot bound elsewhere'] = bad
    bad = dict(good)
    bad[419] = (bad[419][0], bad[419][1], True, 0, ARM64_RELOC_UNSIGNED)
    cases['an unsigned pointer'] = bad
    bad = dict(good)
    bad[1] = (abi['slots'][1][2], int(abi['slots'][1][1], 16), True, 0, ARM64_RELOC_AUTHENTICATED_POINTER)
    cases["the original's deleting destructor in the subclass's slot"] = bad
    for what, entries in cases.items():
        try:
            check_object(abi, None, data=fake_object(entries))
            problems.append(f'accepted {what}')
        except Refused:
            pass
    # the collection gate: a file whose SHA-256 is not the pinned one must be refused before anything else is read
    import tempfile
    with tempfile.NamedTemporaryFile(suffix='.bin') as tmp:
        tmp.write(b'not the pinned collection')
        tmp.flush()
        try:
            check_kc(abi, tmp.name)
            problems.append('accepted a collection with another SHA-256')
        except Refused:
            pass
    if problems:
        raise Refused('xHCI ABI gate self-test FAILED: ' + '; '.join(problems))
    return (f'xHCI ABI gate self-test: a correct {slots}-slot subclass accepted, {len(cases)} drifted vtables and a changed '
            f'collection refused')


