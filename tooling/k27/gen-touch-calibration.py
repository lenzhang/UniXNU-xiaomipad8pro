"""Generate PianoTouch's calibration header from this unit's Ubuntu touchscreen calibration (or the linear-map fallback).

    gen-touch-calibration.py --out HEADER [--name kUnit] [--none | CALIBRATION.json]

CALIBRATION.json defaults to PIANO_TOUCH_CALIBRATION from the environment or ~/.config/piano/env (the private file that
xiaomipad-8pro-mainline tools/extract-thp-calibration.py makes from the vendor piano_nova_<panel>_thp_config.ini). It is checked
as piano-thp checks it (schema 1, 40 x 60, 10 units per pixel, strictly increasing electrode maps inside their maxima, edge sanity:
src/calibration.cpp and Calibration::validate); a missing or invalid file gives a header without calibration (the kext then uses
its linear map). The header goes to the ignored out/ tree only: it holds the unit's maps. One status line goes to stderr: the panel
the file belongs to and the first 8 hex digits of its SHA-256, never its arrays.
"""
import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

ROWS, COLUMNS, UNITS = 40, 60, 10
PANELS = {26: 'BOE', 4: 'CSOT'}


def configured_path():
    value = os.environ.get('PIANO_TOUCH_CALIBRATION')
    if not value:
        env = Path.home() / '.config/piano/env'
        if env.is_file():
            for line in env.read_text().splitlines():
                if line.startswith('PIANO_TOUCH_CALIBRATION='):
                    value = line.split('=', 1)[1].strip().strip('"').strip("'")
    return Path(os.path.expanduser(os.path.expandvars(value))) if value else None


def integer(value, what):
    if type(value) is not int or value < 0 or value > 1000000:
        raise ValueError(f'{what}: not a bounded nonnegative integer')
    return value


def load(path):
    """The checked calibration as a dict, or raises ValueError (the reason, never a value from the maps)."""
    try:
        doc = json.loads(Path(path).read_text())
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ValueError(f'unreadable ({type(error).__name__})')
    if not isinstance(doc, dict):
        raise ValueError('not a JSON object')
    try:
        if integer(doc['schema'], 'schema') != 1:
            raise ValueError('schema is not 1')
        if integer(doc['rows'], 'rows') != ROWS or integer(doc['columns'], 'columns') != COLUMNS:
            raise ValueError('geometry is not 40 x 60')
        if integer(doc['units_per_pixel'], 'units_per_pixel') != UNITS:
            raise ValueError('units_per_pixel is not 10')
        cal = doc['calibration']
        row_map, column_map = cal['row_map'], cal['column_map']
        if not isinstance(row_map, list) or not isinstance(column_map, list) or len(row_map) != ROWS or len(column_map) != COLUMNS:
            raise ValueError('electrode map lengths differ from the geometry')
        rows = [integer(v, 'row_map') for v in row_map]
        columns = [integer(v, 'column_map') for v in column_map]
        out = {k: integer(cal[k], k) for k in ('row_maximum', 'column_maximum', 'edge_base', 'edge_size', 'edge_gain')}
    except KeyError as error:
        raise ValueError(f'missing {error.args[0]}')
    for name, mapping, maximum in (('row_map', rows, out['row_maximum']), ('column_map', columns, out['column_maximum'])):
        if not 0 < maximum <= 32767:
            raise ValueError(f'{name}: maximum out of range')
        if any(b <= a for a, b in zip(mapping, mapping[1:])):
            raise ValueError(f'{name}: not strictly increasing')
        if any(v * UNITS >= maximum for v in mapping):
            raise ValueError(f'{name}: a position beyond its maximum')
    if out['edge_base'] <= 0 or out['edge_size'] <= 0 or 2 * out['edge_size'] >= min(out['row_maximum'], out['column_maximum']):
        raise ValueError('edge parameters out of range')
    vendor = doc.get('project_vendor_id')
    if vendor is not None:
        integer(vendor, 'project_vendor_id')
    invert = doc.get('invert_y')
    if invert is not None and type(invert) is not bool:
        raise ValueError('invert_y is not a boolean')
    out.update(row_map=rows, column_map=columns, project_vendor_id=-1 if vendor is None else vendor,
               invert_y=-1 if invert is None else int(invert))
    return out


def header(cal, sha, name, source):
    lines = ['// Generated by tooling/k27/gen-touch-calibration.py: ' + source + '. Never committed (out/ is ignored).',
             '#pragma once', '#include "TouchMatrix.h"', 'namespace pianotouch {']
    if cal is None:
        lines += [f'constexpr bool {name}CalibrationPresent = false;', f'constexpr char {name}CalibrationSha[] = "none";',
                  f'constexpr Calibration {name}Calibration = {{}};']
    else:
        rows = ', '.join(str(v) for v in cal['row_map'])
        columns = ', '.join(str(v) for v in cal['column_map'])
        lines += [f'constexpr bool {name}CalibrationPresent = true;', f'constexpr char {name}CalibrationSha[] = "{sha}";',
                  f'constexpr Calibration {name}Calibration = {{true, {{{rows}}}, {{{columns}}}, {cal["row_maximum"]}, '
                  f'{cal["column_maximum"]}, {cal["edge_base"]}, {cal["edge_size"]}, {cal["edge_gain"]}, '
                  f'{cal["project_vendor_id"]}, {cal["invert_y"]}}};']
    lines += ['}  // namespace pianotouch', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--name', default='kUnit', help='the generated names\' prefix (kUnit: kUnitCalibration, ...)')
    parser.add_argument('--none', action='store_true', help='no calibration (PIANO_TOUCH_CALIBRATION set empty): the linear map')
    parser.add_argument('calibration', nargs='?', type=Path)
    args = parser.parse_args()
    path = None if args.none else args.calibration or configured_path()
    cal, sha = None, 'none'
    if args.none:
        status, source = 'calibration: none (PIANO_TOUCH_CALIBRATION empty): linear map', 'no calibration (linear map)'
    elif path is None:
        status, source = 'calibration: none (PIANO_TOUCH_CALIBRATION not set): linear map', 'no calibration (linear map)'
    elif not path.is_file():
        status, source = 'calibration: none (PIANO_TOUCH_CALIBRATION names no file): linear map', 'no calibration (linear map)'
    else:
        sha = hashlib.sha256(path.read_bytes()).hexdigest()[:8]
        try:
            cal = load(path)
            panel = PANELS.get(cal['project_vendor_id'], 'unknown' if cal['project_vendor_id'] >= 0 else 'not recorded')
            status = (f'calibration: unit file (panel {panel}, sha256 {sha}), electrode maps, edge {cal["edge_size"] // UNITS} px'
                      + ('' if cal['invert_y'] < 0 else f', invert_y {bool(cal["invert_y"])}'))
            source = f'the unit\'s calibration (sha256 {sha}...)'
        except ValueError as error:
            status = f'calibration: INVALID unit file (sha256 {sha}): {error}: linear map'
            cal, source = None, 'an invalid calibration: linear map'
    text = header(cal, sha, args.name, source)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.is_file() or args.out.read_text() != text:
        args.out.write_text(text)
    print(status, file=sys.stderr)


if __name__ == '__main__':
    main()
