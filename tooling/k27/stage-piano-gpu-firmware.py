"""Stage piano's gen80000 GPU firmware for PianoA830 (never committed).

    stage-piano-gpu-firmware.py [--source DIR] [--no-firmware]

Pattern: UniXNU-Pagani_SM8750 scripts/build-pagani-gpu.py (25b1109, BSD-2-Clause-Patent). The four images (GMU, SQE, AQE and piano's
own signed ZAP) come from the tablet's stock vendor_a/odm_a copies in --source (default PIANO_GPU_FW, else
../xiaomipad-8pro-mainline/firmware), which must match both package/PianoA830/board/piano-gpu-firmware.json and, when present, the
source's own piano-gpu.json. They are copied into the ignored out/native-kexts/PianoA830/firmware and embedded from there:
out/native-kexts/PianoA830/gen/PianoA830Firmware.c (page-aligned .incbin, sizes as literals, so no relocation) and
PianoGpuFirmwarePins.h (the SHA-256 pins S0 checks; written with or without the firmware). --no-firmware leaves the images out:
the driver's weak zero-length defaults stay and S0 refuses to start (A830S0StepFirmware).
"""
import argparse
import hashlib
import json
import os
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PINS = REPO / 'package/PianoA830/board/piano-gpu-firmware.json'
OUT = REPO / 'out/native-kexts/PianoA830'


def fail(message):
    raise SystemExit('stage-piano-gpu-firmware: ' + message)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    default = os.environ.get('PIANO_GPU_FW') or str(REPO.parents[0] / 'xiaomipad-8pro-mainline/firmware')
    if not Path(default).is_dir():   # a worktree under .claude/worktrees: the checkout's sibling
        default = str(Path.home() / 'Downloads/XiaomiPad8Pro-Ubuntu/xiaomipad-8pro-mainline/firmware')
    parser.add_argument('--source', type=Path, default=Path(default))
    parser.add_argument('--no-firmware', action='store_true')
    args = parser.parse_args()
    pins = json.loads(PINS.read_text())['firmware']['files']
    gen, firmware = OUT / 'gen', OUT / 'firmware'
    gen.mkdir(parents=True, exist_ok=True)
    header = ['// Generated by tooling/k27/stage-piano-gpu-firmware.py from package/PianoA830/board/piano-gpu-firmware.json.',
              '#pragma once', '#include <stdint.h>']
    for name, pin in pins.items():
        digest = bytes.fromhex(pin['sha256'])
        header.append(f'inline constexpr uint8_t PIANO_GPU_FW_{pin["header"]}_SHA256[32]={{' + ','.join(f'{b:#04x}' for b in digest)
                      + f'}};  // {name}, {pin["bytes"]} bytes')
    (gen / 'PianoGpuFirmwarePins.h').write_text('\n'.join(header) + '\n')
    source = gen / 'PianoA830Firmware.c'
    if args.no_firmware:
        source.unlink(missing_ok=True)
        print('stage-piano-gpu-firmware: no firmware (S0 refuses to start); pins header written')
        return
    upstream = {}
    if (args.source / 'piano-gpu.json').is_file():
        upstream = json.loads((args.source / 'piano-gpu.json').read_text()).get('files', {})
    firmware.mkdir(parents=True, exist_ok=True)
    lines = ['// Generated by tooling/k27/stage-piano-gpu-firmware.py: piano\'s pinned gen80000 images, page aligned, from the ignored',
             '// out/native-kexts/PianoA830/firmware copies (never committed). Strong definitions over the driver\'s weak defaults.',
             '__asm__(".section __DATA,__const\\n"']
    report = {}
    for name, pin in pins.items():
        path = args.source / pin['source']
        data = path.read_bytes() if path.is_file() else b''
        digest = hashlib.sha256(data).hexdigest()
        if len(data) != pin['bytes'] or digest != pin['sha256']:
            fail(f'{path} is missing or does not match its pin ({pin["bytes"]} bytes, sha256 {pin["sha256"]})')
        mirror = upstream.get(pin['source'])
        if mirror and (mirror['bytes'], mirror['sha256']) != (pin['bytes'], pin['sha256']):
            fail(f'{pin["source"]}: {args.source}/piano-gpu.json pins another image than piano-gpu-firmware.json')
        copy = firmware / name
        if not copy.is_file() or copy.read_bytes() != data:
            shutil.copyfile(path, copy)
        label = '_' + pin['symbol']
        lines += [f'    ".p2align 12\\n.globl {label}\\n{label}:\\n.incbin \\"{copy.resolve()}\\"\\n"',
                  f'    ".p2align 3\\n.globl {label}_size\\n{label}_size:\\n.quad {pin["bytes"]}\\n"']
        report[name] = {'bytes': len(data), 'sha256': digest, 'symbol': pin['symbol'], 'from': str(path)}
    lines.append('    );')
    source.write_text('\n'.join(lines) + '\n')
    (OUT / 'firmware-report.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f'stage-piano-gpu-firmware: {len(report)} pinned images staged in {firmware} and {source}')


if __name__ == '__main__':
    main()
