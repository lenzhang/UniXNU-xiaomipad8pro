#!/bin/bash
# Build package/PianoTouch (the NT36532E touch screen on QUP1 SE2: GENI SPI with SE DMA, or SPI by hand; the host download; the
# matrix decoder; a tablet pointer for macOS) as a k27 native kext: the host tests first (tests/geni_spi_host.c: GeniSpi.c against
# its register model; tests/touch_host.cpp: the protocol against an NT36532E model, the staged images downloaded into it, the
# decoder, the HID report, the clock decoding), then the panel images staged and embedded, then the objects in
# out/native-kexts/PianoTouch for tooling/k27/kext/PianoTouch.json. Prints out/k27/kext/PianoTouch.json (resolved) last.
# Inert without the boot argument piano-touch (package/PianoTouch/PianoTouch.cpp, docs/drivers/touch.md).
#   environment: K27_TREE (the k27 build tree, read only: compile recipes, out/x12377/inc-hid), K27_OBJ (default k27-native-obj),
#                CC/CXX (host compilers for the tests), PIANO_TOUCH_FW_DIR (the directory with novatek_nt36532_piano_fw_{boe,csot}.bin;
#                default ../xiaomipad-8pro-mainline's firmware/novatek/piano), PIANO_TOUCH_NO_FIRMWARE=1 (build without them: step 5
#                then stops with "no usable image")
# The images (the stock OS3.0.303.0 odm_a files, pinned below as xiaomipad-8pro-mainline firmware/piano-input.json pins them) are
# Novatek's/Xiaomi's and never committed: they are copied into the ignored out/native-kexts/PianoTouch/firmware and .incbin'd from
# there. A missing one is left out (with a warning); one that is not the pinned file stops the build.
set -euo pipefail
D=$(cd "$(dirname "$0")/../.." && pwd)
K=${K27_TREE:-$HOME/Downloads/XiaomiPad8Pro-Ubuntu/droidvm-build/macOS-DroidVM}
HID=$K/out/x12377/inc-hid
P=$D/package/PianoTouch; O=$D/out/native-kexts/PianoTouch
[ -f "$HID/IOKit/hid/IOHIDDevice.h" ] || { echo "Error: no IOKit/hid headers at $HID" >&2; exit 1; }
mkdir -p "$O/host-tests" "$O/gen" "$O/firmware" "$D/out/k27/kext"
FW_DIR=${PIANO_TOUCH_FW_DIR:-$D/../xiaomipad-8pro-mainline/firmware/novatek/piano}
[ -d "$FW_DIR" ] || FW_DIR=$HOME/Downloads/XiaomiPad8Pro-Ubuntu/xiaomipad-8pro-mainline/firmware/novatek/piano   # a worktree
GEN=$O/gen/PianoTouchFirmware.c
printf '%s\n' '// Generated by tooling/k27/build-native-piano-touch.sh: the pinned panel images from the ignored out/ copy (never committed).' > "$GEN.tmp"
STAGED=()
for PANEL in boe:b7999389d49decb14019e24ce68c6fbb0a388e26391b9b0ab913e285c5e44c6b csot:14b30bb7799d273f6c5d967376694c2cbd3056f3939135ceda70ebec64abfa7a; do
  NAME=${PANEL%%:*} SHA=${PANEL#*:} BYTES=245760
  SRC=$FW_DIR/novatek_nt36532_piano_fw_$NAME.bin DST=$O/firmware/novatek_nt36532_piano_fw_$NAME.bin
  if [ "${PIANO_TOUCH_NO_FIRMWARE:-0}" != 1 ] && [ -f "$SRC" ]; then
    [ "$(wc -c < "$SRC" | tr -d ' ')" = "$BYTES" ] && [ "$(shasum -a 256 "$SRC" | cut -d' ' -f1)" = "$SHA" ] \
      || { echo "Error: $SRC is not the pinned image ($BYTES bytes, sha256 $SHA)" >&2; exit 1; }
    cmp -s "$SRC" "$DST" || cp "$SRC" "$DST"
    STAGED+=("$DST")
    printf '%s\n' "__asm__(\".section __DATA,__const\\n.p2align 3\\n.globl _piano_touch_firmware_$NAME\\n_piano_touch_firmware_$NAME:\\n.incbin \\\"$DST\\\"\\n.p2align 3\\n.globl _piano_touch_firmware_${NAME}_size\\n_piano_touch_firmware_${NAME}_size:\\n.quad $BYTES\\n\");" \
      "const char piano_touch_firmware_${NAME}_sha[] = \"$SHA\";" >> "$GEN.tmp"
  else
    [ "${PIANO_TOUCH_NO_FIRMWARE:-0}" = 1 ] || echo "Warning: no $SRC: PianoTouch built without the $NAME image (step 5 stops on that panel)" >&2
    rm -f "$DST"
    printf '%s\n' "__asm__(\".section __DATA,__const\\n.p2align 3\\n.globl _piano_touch_firmware_$NAME\\n_piano_touch_firmware_$NAME:\\n.quad 0\\n.globl _piano_touch_firmware_${NAME}_size\\n_piano_touch_firmware_${NAME}_size:\\n.quad 0\\n\");" \
      "const char piano_touch_firmware_${NAME}_sha[] = \"none\";" >> "$GEN.tmp"
  fi
done
cmp -s "$GEN.tmp" "$GEN" && rm -f "$GEN.tmp" || mv "$GEN.tmp" "$GEN"
"${CC:-cc}" -std=c11 -Wall -Wextra -Werror "$P/tests/geni_spi_host.c" "$P/GeniSpi.c" -o "$O/host-tests/geni_spi_host"
"$O/host-tests/geni_spi_host" >&2 || { echo "Error: GeniSpi host tests failed" >&2; exit 1; }
"${CXX:-c++}" -std=c++20 -Wall -Wextra -Werror -I "$P" -I "$D/package/PianoDwc3" "$P/tests/touch_host.cpp" -o "$O/host-tests/touch_host"
"$O/host-tests/touch_host" ${STAGED[@]+"${STAGED[@]}"} >&2 || { echo "Error: PianoTouch host tests failed" >&2; exit 1; }
python3 "$D/tooling/k27/build-native-kext.py" PianoTouch "$P/PianoTouch.cpp" "$P/GeniSpi.c" "$D/tooling/k27/NativeKextGlue.cpp" "$GEN" \
  -I "$P" -I "$D/package/PianoDwc3" -I "$HID" -I "$K/out/x12377/inc-gfx" -I "$K/out/x12377/storage-abi/include" \
  -D U:TARGET_OS_OSX -D TARGET_OS_OSX=1 --obj "${K27_OBJ:-k27-native-obj}" >&2
KERNEL=${K27_KERNEL:-$K/out/k27/kernel-k27-0059-native.macho}
# IOHIDDevice's symbols come from IOHIDFamily, the GCC lock word from PianoA830 (both libraries of the descriptor), resolved by the KC link.
[ ! -f "$KERNEL" ] || python3 "$D/tooling/k27/check-kext-imports.py" "$O/objects.json" "$KERNEL" --library-prefix __ZN11IOHIDDevice \
  --library-prefix __ZNK11IOHIDDevice --library-prefix __ZTV11IOHIDDevice --library-prefix _sm8750_gcc_vote_owner | cut -c1-160 >&2
sed "s#@OUT@#$D/out#" "$D/tooling/k27/kext/PianoTouch.json" > "$D/out/k27/kext/PianoTouch.json"
echo "$D/out/k27/kext/PianoTouch.json"
