#!/bin/bash
# The Metal plugin for piano's real GPU natively (docs/drivers/gpu-userspace.md): the VM's NativeAdrenoMetal.bundle, its plugin,
# frontend and Rust bridge (metal2vulkan) unchanged, with Turnip rebuilt against Adreno830's kernel ABI (NativeAdrenoABI.h v2), so
# that Turnip's darwin backend talks to the native accelerator's user client (AGXAccelerator, open type 0x4147, the NTNL tunnel)
# instead of the VM's virtio-gpu context.
#
#   tooling/metal/build-turnip-a830.sh        -> out/turnip-a830/NativeAdrenoMetal.bundle (arm64e-apple-macos14.0, ad hoc signed)
#
# Then tooling/k27/stage-soft-metal.py --out out/turnip-a830/stage out/turnip-a830/NativeAdrenoMetal.bundle puts it into a Data seed
# and its CDHashes into a trust cache; tooling/k27/build-native-image.sh does both by itself when PianoA830 is linked.
#
# Inputs, all read only (nothing is written outside out/turnip-a830):
#   - Mesa: the VM-era work tree $TURNIP_TREE/.cache/mesa-work (Mesa cecc0e9 + UniXNU-turnip's 21 patches/mesa + the k27 tree's
#     patches/mesa-macos; tooling/metal/UPSTREAM), copied to out/turnip-a830/mesa, then tooling/metal/turnip-a830/mesa/*.patch;
#   - the ABI: package/PianoA830/NativeAdrenoABI.h when the kernel side has it, else $ADRENO830_TREE/NativeAdrenoABI.h, plus
#     tooling/metal/turnip-a830/NativeAdrenoABICompat.h for the one v1/Adreno740 name the backend uses and v2 lacks;
#   - the plugin: $PIANO_K27_TREE/overlay/metal/NativeAdrenoMetalPlugin.mm, the frontend $TURNIP_TREE/drivers/AdrenoMetal through
#     $PIANO_K27_TREE/scripts/piano-frontend-patch.py and then tooling/metal/turnip-a830/frontend/*.patch (2026-11-11: the console after a
#     login; with them the plugin is linked here, no longer the VM's binary), the prebuilt bridge $PIANO_K27_TREE/out/metal/bridge/libnative_metal_bridge.a (metal2vulkan,
#     GPL-2.0+/LGPL-3.0+, built on the private build host by $PIANO_K27_TREE/scripts/build-metal-bridge-macos.py), as $PIANO_K27_TREE/build-metal-plugin-piano.sh;
#   - $TURNIP_TREE/scripts/macho-weak-self-binds.py (dyld's flat lookups of Mesa's weak entry points).
# Provenance and licences: tooling/metal/UPSTREAM.
#
#   environment: DEVELOPER_DIR (default /Applications/Xcode.app/Contents/Developer), PIANO_K27_TREE (tooling/k27/k27-tree.sh),
#                TURNIP_TREE (default: UniXNU-turnip next to the k27 tree), ADRENO830_TREE,
#                PIANO_A830_ABI (another NativeAdrenoABI.h), PYTHON315 (the venv's interpreter), JOBS (ninja -j)
set -euo pipefail
D=$(cd "$(dirname "$0")/../.." && pwd)
export DEVELOPER_DIR=${DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}
H=$HOME/Downloads/XiaomiPad8Pro-Ubuntu
. "$D/tooling/k27/k27-tree.sh"; K=$PIANO_K27_TREE
T=${TURNIP_TREE:-$(dirname "$K")/UniXNU-turnip}   # default: the UniXNU-turnip checkout next to the k27 tree
A=${ADRENO830_TREE:-$H/unixnu-research/Adreno830}
P=$D/tooling/metal/turnip-a830
O=$D/out/turnip-a830
# Adreno830 1a13210's NativeAdrenoABI.h and the VM's bridge (out/metal/bridge, 2026-11-10 01:32): what this was built and checked with.
ABI_PIN=20ac9298bb390d86788c1fc58155e1f9581ffa942e222752efc95c67cb5670d2
BRIDGE_PIN=81d46fae51eea467eac152cbc7817658986c9d7bb25ae54fa40cba0c3b516d4d
SDK=$(xcrun --sdk macosx --show-sdk-path)
mkdir -p "$O/abi" "$O/plugin"

put() {   # put SRC DEST: copy only when different, so an unchanged input keeps its time and nothing rebuilds
  cmp -s "$1" "$2" || cp "$1" "$2"
}
stale() {   # stale OUT IN...: OUT is missing or older than one of IN
  local out=$1; shift
  [ -e "$out" ] || return 0
  for i in "$@"; do [ "$i" -nt "$out" ] && return 0; done
  return 1
}
sha() { shasum -a 256 "$1" | cut -d' ' -f1; }

# 1. The ABI directory Turnip's darwin backend is built with (-Dtu-darwin-abi-dir): the kernel's header as it is, a wrapper of the
#    name the backend includes, the compat names, and the k27 tree's virtgpu ABI header (DroidVMVirtgpuABI.h, the name the backend
#    includes; the virtgpu backend still compiles, unused: it runs only with TU_DARWIN_VIRTGPU=1).
ABI=${PIANO_A830_ABI:-}
if [ -z "$ABI" ]; then
  ABI=$A/NativeAdrenoABI.h
  [ -f "$D/package/PianoA830/NativeAdrenoABI.h" ] && ABI=$D/package/PianoA830/NativeAdrenoABI.h
fi
[ -f "$ABI" ] || { echo "no NativeAdrenoABI.h at $ABI (ADRENO830_TREE or PIANO_A830_ABI)" >&2; exit 1; }
grep -Eq 'NativeAdrenoAbiVersion *= *2,' "$ABI" || { echo "$ABI is not ABI version 2" >&2; exit 1; }
[ "$(sha "$ABI")" = "$ABI_PIN" ] || echo "note: $ABI differs from Adreno830 1a13210's (sha256 $(sha "$ABI")); building against it"
put "$ABI" "$O/abi/NativeAdrenoABI.v2.h"
put "$P/NativeAdrenoABICompat.h" "$O/abi/NativeAdrenoABICompat.h"
put "$K/out/x12377/src-gpu/drivers/NativeAdreno/DroidVMVirtgpuABI.h" "$O/abi/DroidVMVirtgpuABI.h"
{ echo "/* Generated by tooling/metal/build-turnip-a830.sh: the kernel's ABI ($ABI, sha256 $(sha "$ABI")) and the compat names. */"
  echo '#include "NativeAdrenoABI.v2.h"'
  grep -q NativeAdrenoParamsOwnedCoherent "$ABI" || echo '#include "NativeAdrenoABICompat.h"'
} > "$O/abi/NativeAdrenoABI.h.new"
put "$O/abi/NativeAdrenoABI.h.new" "$O/abi/NativeAdrenoABI.h"
rm -f "$O/abi/NativeAdrenoABI.h.new"

# 2. Mesa: the VM's tree, copied again (rsync restores what the patches changed) and patched, when the tree or the patches changed.
SRC=$T/.cache/mesa-work
[ -f "$SRC/meson.build" ] || { echo "no Mesa work tree at $SRC (TURNIP_TREE)" >&2; exit 1; }
PATCHES=("$P"/mesa/*.patch)
MESA_ID=$( { echo "$SRC"; cat "${PATCHES[@]}"; } | shasum -a 256 | cut -c1-16)
if [ "$(cat "$O/mesa.stamp" 2>/dev/null)" != "$MESA_ID" ] ||
   [ -n "$(find "$SRC" -path "$SRC/.git" -prune -o -type f -newer "$O/mesa.stamp" -print -quit)" ]; then
  rsync -a --delete --exclude /.git "$SRC/" "$O/mesa/"
  for p in "${PATCHES[@]}"; do patch -s -p1 -d "$O/mesa" < "$p"; done
  echo "$MESA_ID" > "$O/mesa.stamp"
  echo "mesa: $SRC + ${#PATCHES[@]} patch(es) -> $O/mesa"
fi

# 3. Meson in a venv of the VM build's versions (its configure log: meson 1.12.1; mako 1.4.3, PyYAML 6.0.3, packaging 26.3).
if [ ! -x "$O/venv/bin/meson" ]; then
  "${PYTHON315:-/opt/homebrew/opt/python@3.15/bin/python3.15}" -m venv "$O/venv"
  "$O/venv/bin/pip" install -q --disable-pip-version-check meson==1.12.1 mako==1.4.3 PyYAML==6.0.3 packaging==26.3
fi

# 4. Turnip, with the VM's cross file and options (UniXNU-turnip build-turnip-macos-piano.py) but this ABI directory.
tool() { xcrun --sdk macosx --find "$1"; }
FLAGS="['-target', 'arm64e-apple-macos14.0', '-isysroot', '$SDK', '-fstack-protector-strong']"
{ printf "[binaries]\nc = '%s'\ncpp = '%s'\nobjc = '%s'\nar = '%s'\nstrip = '%s'\npkg-config = '/usr/bin/false'\n" \
    "$(tool clang)" "$(tool clang++)" "$(tool clang)" "$(tool ar)" "$(tool strip)"
  printf "[host_machine]\nsystem = 'darwin'\ncpu_family = 'aarch64'\ncpu = 'arm64'\nendian = 'little'\n"
  printf "[properties]\nneeds_exe_wrapper = true\n[built-in options]\n"
  for k in c_args cpp_args objc_args c_link_args cpp_link_args objc_link_args; do echo "$k = $FLAGS"; done
} > "$O/cross.ini.new"
put "$O/cross.ini.new" "$O/cross.ini"; rm -f "$O/cross.ini.new"
OPTS=(-Dgallium-drivers= -Dvulkan-drivers=freedreno -Dfreedreno-kmds=darwin "-Dtu-darwin-abi-dir=$O/abi"
      -Dplatforms=macos -Dglx=disabled -Degl=disabled -Dgbm=disabled -Dopengl=false -Dgles1=disabled
      -Dgles2=disabled -Dllvm=disabled -Dshared-glapi=disabled -Dxmlconfig=disabled -Dshader-cache=disabled
      -Dtools= -Dbuild-tests=false -Dvideo-codecs= -Dvulkan-layers= -Dlibunwind=disabled -Dlmsensors=disabled
      -Dvalgrind=disabled -Dexpat=disabled -Dzstd=disabled -Dbuildtype=release -Db_ndebug=true
      "-Dtu-builtin-source-id=$(printf '0%.0s' {1..64})" -Dtu-builtin-pack-header= "-Dtu-build-id=$(printf '1%.0s' {1..40})")
for v in $(env | grep -oE '^(IR3_|FD_MESA_|NIR_|MESA_SHADER_|TU_)[A-Za-z0-9_]*' || true); do unset "$v"; done
export PATH="/opt/homebrew/opt/bison/bin:$O/venv/bin:/opt/homebrew/bin:$PATH" CC=$(tool clang) CXX=$(tool clang++) CFLAGS= CXXFLAGS= CPPFLAGS= LDFLAGS=
# Mesa's Python generators iterate sets in places: a fixed hash seed makes two cold builds byte for byte the same (the staged seed's
# identity, and data-persist=2's store with it, then survives a rebuild).
export PYTHONHASHSEED=0
OPTS_ID=$(printf '%s\n' "${OPTS[@]}" | shasum -a 256 | cut -c1-16)
if [ ! -f "$O/build/build.ninja" ]; then
  meson setup "$O/build" "$O/mesa" --wrap-mode=nodownload --cross-file "$O/cross.ini" "${OPTS[@]}" > "$O/configure.log" 2>&1 \
    || { tail -20 "$O/configure.log" >&2; exit 1; }
  echo "$OPTS_ID" > "$O/options.stamp"
elif [ "$(cat "$O/options.stamp" 2>/dev/null)" != "$OPTS_ID" ]; then
  meson configure "$O/build" "${OPTS[@]}" > "$O/configure.log" 2>&1 || { tail -20 "$O/configure.log" >&2; exit 1; }
  echo "$OPTS_ID" > "$O/options.stamp"
fi
ninja -C "$O/build" -j"${JOBS:-$(sysctl -n hw.ncpu)}" > "$O/build.log" 2>&1 \
  || { grep -E 'error:|FAILED' "$O/build.log" | head -40 >&2; exit 1; }
LIB=$O/build/src/freedreno/vulkan/libvulkan_freedreno.dylib
TURNIP=$O/libvulkan_freedreno.dylib
if stale "$TURNIP" "$LIB"; then
  cp "$LIB" "$TURNIP.new"
  python3 "$T/scripts/macho-weak-self-binds.py" "$TURNIP.new"
  # The weak-bind rewrite voids the linker's signature: XNU rejected the stale page in WindowServer in the VM. Ad hoc again.
  codesign -f -s - "$TURNIP.new" 2> /dev/null
  codesign -v "$TURNIP.new"
  mv "$TURNIP.new" "$TURNIP"
fi

# 5. The plugin, as the VM's build-metal-plugin-piano.sh makes it: its plugin and patched frontend over the prebuilt bridge, then this
#    repository's frontend patches (tooling/metal/turnip-a830/frontend/*.patch, applied in order after piano-frontend-patch.py).
#    With frontend patches or the abort reporter the objects are compiled without objc_msgSend selector stubs (-fno-objc-msgsend-selector-stubs): ld 27106.1
#    (ld-1267) lays the linker-made __objc_stubs out in a different order from link to link (2 outcomes in 8 links of the same
#    objects, -reproducible or not), and without them ten links in a row were byte for byte the same. The calls are the classic
#    objc_msgSend ones.
U=$T/drivers/AdrenoMetal
BRIDGE=$K/out/metal/bridge/libnative_metal_bridge.a
[ -f "$BRIDGE" ] || { echo "no bridge at $BRIDGE" >&2; exit 1; }
[ "$(sha "$BRIDGE")" = "$BRIDGE_PIN" ] || echo "note: $BRIDGE is not the bridge this was checked with (sha256 $(sha "$BRIDGE"))"
FRONTEND_PATCHES=()
for p in "$P"/frontend/*.patch; do [ -f "$p" ] && FRONTEND_PATCHES+=("$p"); done
CXX=(xcrun clang++ -target arm64e-apple-macos14.0 -isysroot "$SDK" -fobjc-arc -O2 -std=c++17 -Wno-deprecated-declarations -c
     -x objective-c++ -I "$U")
if [ ${#FRONTEND_PATCHES[@]} -gt 0 ] || [ -f "$P/abort_reporter.mm" ]; then CXX+=(-fno-objc-msgsend-selector-stubs); fi
# A change of the compile flags recompiles both objects.
printf '%s\n' "${CXX[@]}" > "$O/plugin/flags.new"
if ! cmp -s "$O/plugin/flags.new" "$O/plugin/flags"; then rm -f "$O/plugin/plugin.o" "$O/plugin/frontend.o" "$O/plugin/reporter.o"; mv "$O/plugin/flags.new" "$O/plugin/flags"
else rm -f "$O/plugin/flags.new"; fi
if stale "$O/plugin/plugin.o" "$K/overlay/metal/NativeAdrenoMetalPlugin.mm" "$U/NativeBridgeMetalFrontend.h"; then
  "${CXX[@]}" "$K/overlay/metal/NativeAdrenoMetalPlugin.mm" -o "$O/plugin/plugin.o"
fi
python3 "$K/scripts/piano-frontend-patch.py" "$U/NativeBridgeMetalFrontend.mm" "$O/plugin/frontend.mm.new" 2> "$O/plugin/frontend-patch.log"
for p in ${FRONTEND_PATCHES[@]+"${FRONTEND_PATCHES[@]}"}; do
  patch -s "$O/plugin/frontend.mm.new" < "$p" || { echo "frontend patch $p does not apply" >&2; exit 1; }
done
put "$O/plugin/frontend.mm.new" "$O/plugin/frontend.mm"; rm -f "$O/plugin/frontend.mm.new" "$O/plugin/frontend.mm.new.orig"
if stale "$O/plugin/frontend.o" "$O/plugin/frontend.mm" "$U/NativeBridgeMetalFrontend.h" "$U/bridge/NativeMetalObjects.h"; then
  "${CXX[@]}" "$O/plugin/frontend.mm" -o "$O/plugin/frontend.o"
fi
# The abort reporter (tooling/metal/turnip-a830/abort_reporter.mm, ours: NativeSoftMetal's in the desktop's Metal clients) as a third
# object, when present; with it the plugin is always linked here.
EXTRA_OBJECTS=()
if [ -f "$P/abort_reporter.mm" ]; then
  if stale "$O/plugin/reporter.o" "$P/abort_reporter.mm"; then "${CXX[@]}" "$P/abort_reporter.mm" -o "$O/plugin/reporter.o"; fi
  EXTRA_OBJECTS=("$O/plugin/reporter.o")
else
  rm -f "$O/plugin/reporter.o"
fi
EXE=$O/plugin/NativeAdrenoMetal
# ld 27106.1 does not link this reproducibly (two links of the same objects differ in __objc_stubs, 2026-11-11). When both objects
# are byte for byte the VM's and the bridge is the pinned one, the VM's linked executable is taken: the plugin then is exactly the
# one WindowServer ran in the VM (its CDHash already in the VM-era trust cache). PIANO_A830_RELINK=1 links anyway.
VMP=$K/out/metal/plugin
if [ "${PIANO_A830_RELINK:-0}" != 1 ] && [ ${#EXTRA_OBJECTS[@]} = 0 ] && cmp -s "$O/plugin/plugin.o" "$VMP/plugin.o" &&
   cmp -s "$O/plugin/frontend.o" "$VMP/frontend.o" &&
   [ "$(sha "$BRIDGE")" = "$BRIDGE_PIN" ] && [ -f "$VMP/NativeAdrenoMetal.bundle/Contents/MacOS/NativeAdrenoMetal" ]; then
  put "$VMP/NativeAdrenoMetal.bundle/Contents/MacOS/NativeAdrenoMetal" "$EXE"
  PLUGIN_FROM="the VM's linked executable (plugin.o, frontend.o and the bridge byte-identical to its inputs)"
elif stale "$EXE" "$O/plugin/plugin.o" "$O/plugin/frontend.o" "$BRIDGE" ${EXTRA_OBJECTS[@]+"${EXTRA_OBJECTS[@]}"} ||
     [ "${PIANO_A830_RELINK:-0}" = 1 ]; then
  xcrun ld -arch arm64e -platform_version macos 14.0 27.2 -syslibroot "$SDK" -F "$K/overlay/metal/frameworks" \
    -bundle -dead_strip -o "$EXE" "$O/plugin/plugin.o" "$O/plugin/frontend.o" ${EXTRA_OBJECTS[@]+"${EXTRA_OBJECTS[@]}"} "$BRIDGE" \
    -framework Foundation -framework Metal -framework IOSurface -framework IOKit -framework CoreFoundation -framework IOGPU \
    -lobjc -lc++ -lSystem -liconv 2>&1 | { grep -v "was built for newer" || true; }
  PLUGIN_FROM="linked here"
else
  PLUGIN_FROM="linked here earlier"
fi

# 6. The bundle: what the VM's had (Contents/Info.plist, MacOS/NativeAdrenoMetal, MacOS/libvulkan_freedreno.dylib).
B=$O/NativeAdrenoMetal.bundle/Contents
mkdir -p "$B/MacOS"
put "$EXE" "$B/MacOS/NativeAdrenoMetal"
put "$TURNIP" "$B/MacOS/libvulkan_freedreno.dylib"
python3 - "$B/Info.plist" <<'EOF'
import plistlib, sys
data = plistlib.dumps(dict(
    CFBundleIdentifier='org.droidvm.NativeAdrenoMetal', CFBundleExecutable='NativeAdrenoMetal', CFBundlePackageType='BNDL',
    CFBundleVersion='1', CFBundleShortVersionString='1', NSPrincipalClass='NativeAdrenoMetalDevice',
    CFBundleSupportedPlatforms=['MacOSX'], LSMinimumSystemVersion='14.0'), fmt=plistlib.FMT_XML)
try:
    same = open(sys.argv[1], 'rb').read() == data
except FileNotFoundError:
    same = False
if not same:
    open(sys.argv[1], 'wb').write(data)
EOF
if cmp -s "$VMP/NativeAdrenoMetal.bundle/Contents/MacOS/NativeAdrenoMetal" "$B/MacOS/NativeAdrenoMetal"; then
  echo "plugin: byte-identical to the VM's: $PLUGIN_FROM"
else
  echo "plugin: not the VM's binary ($PLUGIN_FROM)"
fi
for f in NativeAdrenoMetal libvulkan_freedreno.dylib; do
  echo "$f: $(codesign -dv --verbose=4 "$B/MacOS/$f" 2>&1 | sed -n 's/^CDHash=//p' | head -1) $(lipo -archs "$B/MacOS/$f") $(stat -f %z "$B/MacOS/$f") bytes"
done
grep -h 'frontend edit skipped' "$O/plugin/frontend-patch.log" || true
echo "$O/NativeAdrenoMetal.bundle (Turnip on $(basename "$(dirname "$ABI")")/NativeAdrenoABI.h v2)"
